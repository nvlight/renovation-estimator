    public static function lineSum(string $title, float|string $price, int $amount): float
    {
        $price = (float) $price;
        if (preg_match('/(\d+(?:[.,]\d+)?)\s*шт/iu', $title, $match)) {
            $perPack = (float) str_replace(',', '.', $match[1]);
            if ($perPack > 0) {
                return (float) ceil(($amount / $perPack) * $price);
            }
        }

        return round($amount * $price, 2);
    }

